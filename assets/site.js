/* Verifika Pro – public site behaviour (D-73, experience principles §7, §8, §10).
   - Parameters come from assets/site-config.js (window.VERIFIKA_SITE), generated by the portal: never typed here.
   - Cookie banner only when analytics are enabled; GA4 (Consent Mode v2, everything denied by default) and Microsoft Clarity
     are loaded ONLY after consent, only on this public site, never inside the signed-in portal.
   - Events of the measurement plan (docs/metrics.md); never a personal value in an event or a URL.
   - UTM: kept for this visit (session storage) and passed to the sign-up and request forms; across visits only with consent. */
(function () {
  'use strict';
  var C = window.VERIFIKA_SITE || {};
  var A = C.analytics || {};
  var LANG = window.VK_LANG === 'fr' ? 'fr' : 'en';
  var T = window.VK_T || {};
  var CONSENT_KEY = 'vk_consent';
  var VISIT_KEY = 'vk_visit';
  var EMAIL_KEY = 'vk_pass_email';
  // version of the list of tools: when it changes, the banner is shown again (§8)
  var TOOLS_VERSION = 'ga4+clarity.1';
  function t(k, d) { return T[k] || d || k; }
  function $(s, r) { return (r || document).querySelector(s); }
  function $$(s, r) { return Array.prototype.slice.call((r || document).querySelectorAll(s)); }
  function store(kind) { try { var s = window[kind]; var k = '__vk'; s.setItem(k, '1'); s.removeItem(k); return s; } catch (e) { return null; } }
  var LS = store('localStorage'); var SS = store('sessionStorage');
  function getJson(s, k) { try { return s ? JSON.parse(s.getItem(k) || 'null') : null; } catch (e) { return null; } }
  function setJson(s, k, v) { try { if (s) s.setItem(k, JSON.stringify(v)); } catch (e) { /* storage full or blocked */ } }

  // ---- parameters ----------------------------------------------------------------------------------------
  function safeHref(u) { return /^https:\/\/[^\s"'<>]+$/i.test(String(u || '')) ? u : ''; }
  $$('[data-cfg-href]').forEach(function (a) { var u = safeHref(C[a.getAttribute('data-cfg-href')]); if (u) { a.href = u; a.hidden = false; a.target = '_blank'; a.rel = 'noopener'; } else a.hidden = true; });
  var legal = C.legal || {};
  $$('[data-cfg]').forEach(function (n) { var v = legal[n.getAttribute('data-cfg')]; if (v) n.textContent = v; });
  $$('[data-cfg-mail]').forEach(function (a) { var v = legal[a.getAttribute('data-cfg-mail')]; if (v && /^[^\s@<>"]+@[^\s@<>"]+$/.test(v)) a.href = 'mailto:' + v; });
  $$('[data-cfg-line]').forEach(function (n) { if (!legal[n.getAttribute('data-cfg-line')]) n.hidden = true; }); // an empty field is never shown
  var promise = C.promise && C.promise[LANG];
  $$('[data-cfg-text="promise"]').forEach(function (n) { if (promise) n.textContent = promise; });
  var dom = $('#domains');
  if (dom && Array.isArray(C.domains)) {
    dom.textContent = '';
    C.domains.forEach(function (d) { var s = document.createElement('span'); s.className = 'chip'; s.textContent = LANG === 'fr' ? d.fr : d.en; dom.appendChild(s); });
  }

  // ---- UTM and landing page (first and last touch) ---------------------------------------------------------
  var UTM = ['utm_source', 'utm_medium', 'utm_campaign', 'utm_content', 'utm_term'];
  function touchNow() {
    var q = new URLSearchParams(location.search); var o = {};
    UTM.forEach(function (k) { var v = q.get(k); if (v && /^[A-Za-z0-9 ._~:\/+-]{1,100}$/.test(v)) o[k] = v; });
    var ref = ''; try { var r = new URL(document.referrer); if (r.host !== location.host) ref = r.host; } catch (e) { ref = ''; }
    if (!Object.keys(o).length && !ref) return null;
    if (ref) o.referrer = ref;
    o.landing_page = location.pathname; o.at = new Date().toISOString().slice(0, 10);
    return o;
  }
  var visit = getJson(SS, VISIT_KEY) || {};
  var now = touchNow();
  if (now) { if (!visit.first) visit.first = now; visit.last = now; setJson(SS, VISIT_KEY, visit); }
  function consented() { var c = getJson(LS, CONSENT_KEY); return !!(c && c.v === TOOLS_VERSION && c.analytics && !expired(c)); }
  function expired(c) { var m = Number(A.cookie_months) || 6; return !c.date || (Date.now() - new Date(c.date).getTime()) > m * 30.5 * 86400000; }
  function utm() {
    var v = getJson(SS, VISIT_KEY) || {};
    if (consented()) { var keep = getJson(LS, 'vk_first_touch'); if (keep && !v.first) v.first = keep; if (v.first && !keep) setJson(LS, 'vk_first_touch', v.first); }
    return v.first || v.last ? v : null;
  }

  // ---- links to the portal: language, UTM, pre-filled account type ----------------------------------------
  $$('a[href^="/app/"]').forEach(function (a) {
    a.addEventListener('click', function () {
      var u = new URL(a.getAttribute('href'), location.origin);
      u.searchParams.set('lang', LANG);
      var v = utm();
      if (v) { if (v.first) u.searchParams.set('u_f', JSON.stringify(v.first)); if (v.last) u.searchParams.set('u_l', JSON.stringify(v.last)); }
      a.href = u.pathname + u.search;
    });
  });

  // ---- events (measurement plan, docs/metrics.md) ------------------------------------------------------
  var queue = [];
  function track(name, params) {
    if (!/^[a-z_]{3,40}$/.test(name)) return;
    var p = {}; Object.keys(params || {}).forEach(function (k) { var v = params[k]; if (/^[a-z_]{2,30}$/.test(k) && /^[A-Za-z0-9_:.-]{1,60}$/.test(String(v))) p[k] = String(v); });
    if (window.gtag && consented()) window.gtag('event', name, p); else if (consented()) queue.push([name, p]);
  }
  window.vkTrack = track;
  $$('[data-cta]').forEach(function (a) { a.addEventListener('click', function () { var x = a.getAttribute('data-cta').split(':'); track('cta_click', { audience: x[0], location: x[1] }); }); });
  $$('[data-tile]').forEach(function (a) { a.addEventListener('click', function () { track('audience_tile_click', { audience: a.getAttribute('data-tile') }); }); });
  $$('[data-booking]').forEach(function (a) { a.addEventListener('click', function () { track('booking_click', { audience: a.getAttribute('data-booking') }); }); });
  $$('details[data-faq]').forEach(function (d) { d.addEventListener('toggle', function () { if (d.open) track('faq_open', { question_id: d.getAttribute('data-faq') }); }); });

  // ---- consent: GA4 Consent Mode v2 + Clarity consent API, nothing before the choice -------------------
  window.dataLayer = window.dataLayer || [];
  function gtag() { window.dataLayer.push(arguments); }
  var loaded = false;
  function cleanLocation() {
    var u = new URL(location.href); var q = new URLSearchParams();
    UTM.forEach(function (k) { var v = u.searchParams.get(k); if (v) q.set(k, v); }); // campaign parameters only, never a token or an e-mail
    return u.origin + u.pathname + (q.toString() ? '?' + q.toString() : '');
  }
  function loadTools() {
    if (loaded || !A.enabled || window.VK_NO_ANALYTICS) return;
    loaded = true;
    if (A.ga4_id) {
      gtag('consent', 'default', { analytics_storage: 'denied', ad_storage: 'denied', ad_user_data: 'denied', ad_personalization: 'denied', wait_for_update: 500 });
      gtag('consent', 'update', { analytics_storage: 'granted' });
      gtag('js', new Date());
      gtag('config', A.ga4_id, { page_location: cleanLocation(), page_referrer: '', allow_google_signals: false, allow_ad_personalization_signals: false,
        cookie_expires: 34128000, cookie_flags: 'SameSite=Lax;Secure' });
      window.gtag = gtag;
      var s = document.createElement('script'); s.async = true; s.src = 'https://www.googletagmanager.com/gtag/js?id=' + encodeURIComponent(A.ga4_id);
      document.head.appendChild(s);
      queue.splice(0).forEach(function (e) { gtag('event', e[0], e[1]); });
    }
    if (A.clarity_id) {
      (function (c, l, a, r, i) {
        c[a] = c[a] || function () { (c[a].q = c[a].q || []).push(arguments); };
        var x = l.createElement(r); x.async = 1; x.src = 'https://www.clarity.ms/tag/' + encodeURIComponent(i);
        var y = l.getElementsByTagName(r)[0]; y.parentNode.insertBefore(x, y);
      })(window, document, 'clarity', 'script', A.clarity_id);
      window.clarity('consent');
    }
  }
  function revoke() {
    if (window.gtag) window.gtag('consent', 'update', { analytics_storage: 'denied' });
    if (window.clarity) window.clarity('consent', false);
    // remove the measurement cookies of this site
    document.cookie.split(';').forEach(function (c) {
      var n = c.split('=')[0].trim();
      if (/^(_ga|_ga_|_clck|_clsk)/.test(n)) ['', '; domain=' + location.hostname, '; domain=.' + location.hostname.replace(/^www\./, '')].forEach(function (d) {
        document.cookie = n + '=; expires=Thu, 01 Jan 1970 00:00:00 GMT; path=/' + d;
      });
    });
    try { if (LS) LS.removeItem('vk_first_touch'); } catch (e) { /* ignore */ }
  }
  var banner = $('#ck-banner'); var modal = $('#ck-modal'); var sw = $('#ck-ana');
  function save(analytics) {
    setJson(LS, CONSENT_KEY, { v: TOOLS_VERSION, analytics: !!analytics, date: new Date().toISOString() });
    if (banner) banner.hidden = true;
    closeModal();
    if (analytics) loadTools(); else revoke();
  }
  var lastFocus = null;
  function openModal() {
    if (!modal) return;
    lastFocus = document.activeElement;
    var c = getJson(LS, CONSENT_KEY);
    if (sw) sw.setAttribute('aria-checked', c && c.analytics ? 'true' : 'false');
    modal.hidden = false;
    var f = $('.ck-close', modal); if (f) f.focus();
  }
  function closeModal() { if (modal && !modal.hidden) { modal.hidden = true; if (lastFocus && lastFocus.focus) lastFocus.focus(); } }
  if (sw) sw.addEventListener('click', function () { sw.setAttribute('aria-checked', sw.getAttribute('aria-checked') === 'true' ? 'false' : 'true'); });
  $$('[data-ck]').forEach(function (b) {
    b.addEventListener('click', function () {
      var k = b.getAttribute('data-ck');
      if (k === 'accept') save(true); else if (k === 'reject') save(false); else if (k === 'choose') openModal();
      else if (k === 'save') save(sw && sw.getAttribute('aria-checked') === 'true'); else if (k === 'close') closeModal();
    });
  });
  $$('[data-cookie-settings]').forEach(function (b) {
    if (!A.enabled) { b.hidden = true; return; } // no measurement tool: nothing to choose
    b.addEventListener('click', openModal);
  });
  if (modal) modal.addEventListener('keydown', function (e) {
    if (e.key === 'Escape') closeModal();
    if (e.key === 'Tab') { var f = $$('button, a[href]', modal).filter(function (x) { return !x.hidden; }); var i = f.indexOf(document.activeElement);
      if (e.shiftKey && i <= 0) { e.preventDefault(); f[f.length - 1].focus(); } else if (!e.shiftKey && i === f.length - 1) { e.preventDefault(); f[0].focus(); } }
  });
  // inside /app/ the measurement runs only before the account exists (sign-up, requests, recruiter application), never for a signed-in page
  if (window.VK_NO_ANALYTICS) A.enabled = false;
  if (A.enabled) {
    var c0 = getJson(LS, CONSENT_KEY);
    if (!c0 || c0.v !== TOOLS_VERSION || expired(c0)) { if (banner) banner.hidden = false; } else if (c0.analytics) loadTools();
  }

  // ---- badges: proof on hover, focus and tap -----------------------------------------------------------
  $$('.bdg').forEach(function (b) {
    var shown = false;
    function seen() { if (!shown) { shown = true; track('badge_proof_view', { level: b.getAttribute('data-level') || 'x' }); } }
    b.addEventListener('mouseenter', seen); b.addEventListener('focus', seen);
    b.addEventListener('click', function () { var open = !b.classList.contains('is-open'); $$('.bdg.is-open').forEach(function (x) { x.classList.remove('is-open'); }); if (open) { b.classList.add('is-open'); seen(); } });
    b.addEventListener('keydown', function (e) { if (e.key === 'Escape') { b.classList.remove('is-open'); b.blur(); } });
  });
  document.addEventListener('click', function (e) { if (!e.target.closest('.bdg')) $$('.bdg.is-open').forEach(function (x) { x.classList.remove('is-open'); }); });

  // ---- tabs (professionals) ------------------------------------------------------------------------------
  var tabs = $$('[role="tab"][data-tab]');
  var proType = 'freelance';
  function pick(tab, focus) {
    tabs.forEach(function (x) { var on = x === tab; x.setAttribute('aria-selected', on ? 'true' : 'false'); x.tabIndex = on ? 0 : -1; var p = document.getElementById(x.getAttribute('aria-controls')); if (p) p.hidden = !on; });
    proType = tab.getAttribute('data-tab') === 'job' ? 'job_seeker' : 'freelance';
    if (focus) tab.focus();
  }
  tabs.forEach(function (tab, i) {
    tab.addEventListener('click', function () { pick(tab); track('tab_switch', { section: 'professionals', tab: tab.getAttribute('data-tab') }); });
    tab.addEventListener('keydown', function (e) { var d = e.key === 'ArrowRight' ? 1 : (e.key === 'ArrowLeft' ? -1 : 0); if (d) { e.preventDefault(); pick(tabs[(i + d + tabs.length) % tabs.length], true); } });
  });

  // ---- Verifika Pass form: inline check, the button says the next step -------------------------------------
  var form = $('#pass-form');
  if (form) {
    var input = $('#pemail'); var label = $('#pass-label'); var wrap = input.closest('.input-wrap'); var btn = $('#pass-submit');
    var empty = label.textContent;
    var started = false;
    function valid() { return /^[^\s@]+@[^\s@]+\.[^\s@]{2,}$/.test(input.value.trim()); }
    function refresh() { var ok = valid(); wrap.classList.toggle('is-valid', ok); label.textContent = ok ? t('js.btn_valid', 'Create my free profile') : empty; input.setAttribute('aria-invalid', input.value && !ok ? 'true' : 'false'); }
    input.addEventListener('input', function () { refresh(); if (!started && input.value) { started = true; } });
    form.addEventListener('submit', function (e) {
      e.preventDefault();
      if (!valid()) { input.focus(); return; }
      btn.disabled = true; label.textContent = t('js.btn_sending', 'Opening your sign-up…');
      track('sign_up_start', { audience: 'professional', kind: proType });
      // the address goes to the sign-up form in the body of a request (never in an address, never in an event), then is deleted
      try { if (SS) SS.setItem(EMAIL_KEY, input.value.trim()); } catch (x) { /* the form will ask again */ }
      var u = new URL('/app/', location.origin);
      u.searchParams.set('page', 'join'); u.searchParams.set('kind', 'person'); u.searchParams.set('type', proType); u.searchParams.set('lang', LANG);
      var v = utm(); if (v) { if (v.first) u.searchParams.set('u_f', JSON.stringify(v.first)); if (v.last) u.searchParams.set('u_l', JSON.stringify(v.last)); }
      location.href = u.pathname + u.search;
    });
  }

  // ---- invite a professional: share or copy the link of this section ----------------------------------------
  var inv = $('#invite-btn');
  if (inv) inv.addEventListener('click', function () {
    track('invite_click', { location: 'professionals' });
    var link = (C.site_url || 'https://verifika.pro/') + (LANG === 'fr' ? 'fr/' : '') + '?utm_source=invite&utm_medium=referral&utm_campaign=professionals#professionals';
    var done = $('#invite-done');
    if (navigator.share) { navigator.share({ title: t('js.app_title', 'Verifika Pro'), text: t('js.invite_text', ''), url: link }).catch(function () { /* cancelled */ }); return; }
    if (navigator.clipboard) navigator.clipboard.writeText(link).then(function () { if (done) done.textContent = ' ' + t('js.invite_copied', 'Link copied.'); });
  });

  // ---- cards: soft light following the mouse (desktop only) ------------------------------------------------
  if (window.matchMedia && window.matchMedia('(hover: hover) and (pointer: fine)').matches) {
    $$('.spot').forEach(function (c) { c.addEventListener('mousemove', function (e) { var r = c.getBoundingClientRect(); c.style.setProperty('--mx', (e.clientX - r.left) + 'px'); c.style.setProperty('--my', (e.clientY - r.top) + 'px'); }); });
  }

  // ---- story complete, current chapter in the navigation ---------------------------------------------------
  if ('IntersectionObserver' in window) {
    var end = $('.story-end');
    if (end) { var io = new IntersectionObserver(function (es) { es.forEach(function (x) { if (x.isIntersecting) { track('story_complete', { section: 'journey' }); io.disconnect(); } }); }); io.observe(end); }
    var links = $$('.main-nav .nv');
    var cur = new IntersectionObserver(function (es) {
      es.forEach(function (x) { if (x.isIntersecting) links.forEach(function (l) { l.classList.toggle('is-current', l.getAttribute('href') === '#' + x.target.id); }); });
    }, { rootMargin: '-45% 0px -50% 0px' });
    ['companies', 'agencies', 'professionals', 'recruiters', 'verification'].forEach(function (id) { var s = document.getElementById(id); if (s) cur.observe(s); });
  }
})();
